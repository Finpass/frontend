export const fmt = (s: string, p: Record<string, string | number> = {}) =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => String(p[k] ?? ""));

export const pick = (lang: Lang, enText: string | undefined, idText: string | undefined) =>
  (lang === "id" ? idText ?? enText : enText ?? idText) ?? "";

export const normalizeLang = (v: string | null): Lang => (v === "en" ? "en" : "id");

/** Flattened key paths, used to prove both languages define the same keys. */
export function keyPaths(o: unknown, prefix = ""): string[] {
  if (typeof o !== "object" || o === null) return [prefix];
  return Object.entries(o).flatMap(([k, v]) => keyPaths(v, prefix ? `${prefix}.${k}` : k));
}
